"""Offline stand-in for the model, used to exercise the pipeline without keys.

This is deliberately *not* a semantic reconstruction. It applies static cleaning
to whatever code text the prompt contains and emits a response in the same
wire format the real provider uses, so prompting, caching, validation,
execution, checkpointing, QA and reporting can all be tested end to end.

Every case it produces is marked ``needs_review: true`` and every run is tagged
``provider=stub`` in the report, so stub output can never be mistaken for
model-reconstructed data.
"""
from __future__ import annotations

import ast
import re

from . import reconstruct, textclean

_SECTION = re.compile(
    r"^--- (BUGGY CODE|FIXED CODE)(?: block (\d+) of \d+)? ---$\n(.*?)(?=^--- |\Z)",
    re.S | re.M,
)

# Crude line-structure recovery for flattened cells. The real provider is
# expected to do this properly by reading the code; this only keeps the stub
# from producing guaranteed syntax errors.
_SPLIT_BEFORE = re.compile(
    r"(?<!^)(?<![\w.])(?=(?:from\s+[\w.]+\s+import|import\s+[\w.]+|"
    r"print\(|for\s+\w+\s+in\s|if\s+|def\s+\w+\(|class\s+\w+|return\s|"
    r"qc\.|circuit\.|backend\s*=|result\s*=|job\s*=|counts\s*=))"
)


def _unflatten(text: str) -> str:
    out = []
    for line in text.split("\n"):
        if len(line) > 120 and line.count("\n") == 0:
            line = _SPLIT_BEFORE.sub("\n", line)
        out.append(line)
    return "\n".join(out)


def _collect(prompt: str, want: str) -> str:
    blocks = [m.group(3) for m in _SECTION.finditer(prompt) if m.group(1) == want]
    if not blocks:
        return ""
    # Prefer the longest block; concatenating unrelated blocks creates nonsense.
    return max(blocks, key=len)


def _build(raw: str) -> str:
    if not raw.strip():
        return ""
    body, _ = textclean.clean_code_cell(_unflatten(raw))
    body, _ = textclean.repair_syntax(body, 25)
    try:
        ast.parse(body)
    except (SyntaxError, ValueError):
        return body  # validation layer will catch and report it
    era = reconstruct.detect_api_era(body)
    imports = []
    for name in reconstruct.undefined_names(body):
        imp = reconstruct.resolve_import(name, era)
        if imp and imp not in imports:
            imports.append(imp)
    return ("\n".join(imports) + "\n\n" + body).strip() if imports else body.strip()


def generate(user_prompt: str) -> str:
    buggy = _build(_collect(user_prompt, "BUGGY CODE"))
    fixed = _build(_collect(user_prompt, "FIXED CODE"))
    era = reconstruct.detect_api_era(buggy + "\n" + fixed)
    return (
        "<BUGGY_PY>\n" + buggy + "\n</BUGGY_PY>\n"
        "<FIXED_PY>\n" + fixed + "\n</FIXED_PY>\n"
        "<META>\n"
        "needs_review: true\n"
        f"api_era: {era}\n"
        "bug_summary: not determined (offline stub, no semantic reconstruction)\n"
        "fix_summary: not determined (offline stub, no semantic reconstruction)\n"
        "reason: generated by the offline stub provider; static cleaning only\n"
        "</META>\n"
    )
